/**
 * Compiles contracts/TradeSimulator.sol with solc-js and writes the runtime bytecode + ABI
 * to src/sim/bytecode.ts. The contract is never deployed; it is injected via eth_call state override.
 * Usage: npm run build:sim
 */
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
const require = createRequire(import.meta.url);
const solc = require("solc");

const source = readFileSync(new URL("../contracts/TradeSimulator.sol", import.meta.url), "utf8");
const input = {
  language: "Solidity",
  sources: { "TradeSimulator.sol": { content: source } },
  settings: {
    optimizer: { enabled: true, runs: 200 },
    viaIR: true,
    evmVersion: "cancun",
    outputSelection: { "*": { TradeSimulator: ["abi", "evm.deployedBytecode.object"] } },
  },
};
const out = JSON.parse(solc.compile(JSON.stringify(input)));
const errors = (out.errors ?? []).filter((e: any) => e.severity === "error");
for (const e of out.errors ?? []) console.error(e.formattedMessage);
if (errors.length) process.exit(1);
const c = out.contracts["TradeSimulator.sol"].TradeSimulator;
const file = `// AUTO-GENERATED by scripts/build-simulator.ts from contracts/TradeSimulator.sol (solc ${solc.version()}). Do not edit.
export const TRADE_SIMULATOR_RUNTIME = "0x${c.evm.deployedBytecode.object}" as const;
export const TRADE_SIMULATOR_ABI = ${JSON.stringify(c.abi, null, 2)} as const;
`;
writeFileSync(new URL("../src/sim/bytecode.ts", import.meta.url), file);
console.log(`wrote src/sim/bytecode.ts (${c.evm.deployedBytecode.object.length / 2} bytes)`);
