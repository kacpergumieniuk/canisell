/**
 * Regenerates src/sample.ts (the free /v1/sample response and Bazaar output example) from a live check.
 * Usage: npx tsx scripts/make-sample.ts <tokenAddress>
 */
import { writeFileSync } from "node:fs";
import { makeClients } from "../src/chain/client.ts";
import { loadConfig } from "../src/config.ts";
import { checkToken, parseTokenAddress } from "../src/risk/verdict.ts";

const cfg = loadConfig(process.env);
const v = await checkToken(makeClients(cfg), parseTokenAddress(process.argv[2]), { simUsd: cfg.simUsd });
const json = JSON.stringify(v, null, 2);
writeFileSync(
  new URL("../src/sample.ts", import.meta.url),
  `// GENERATED by scripts/make-sample.ts from a live check; served by GET /v1/sample.\nexport const SAMPLE_VERDICT = ${json} as const;\n`,
);
console.log(`${v.token.symbol}: ${v.verdict} ${v.score}`);
